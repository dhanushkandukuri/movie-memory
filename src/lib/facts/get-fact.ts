import { randomUUID } from "node:crypto";

// A fact younger than this is reused instead of generating a new one.
export const CACHE_WINDOW_MS = 60_000;

// How long a generation lock is valid. Has to be longer than the slowest
// possible OpenAI call (20s overall deadline in lib/openai.ts), otherwise a
// second request could take the lock over while the first is still working.
export const LOCK_TTL_MS = 30_000;

// How long a request waits for someone else's in-flight generation.
const WAIT_FOR_OTHER_REQUEST_MS = 20_000;
const POLL_INTERVAL_MS = 300;

export type Fact = {
  id: string;
  movieTitle: string;
  content: string;
  createdAt: Date;
};

export type FactSource =
  | "generated" // brand new fact from OpenAI
  | "cache" // a fact less than 60s old, possibly generated by a parallel request
  | "fallback"; // an older fact, returned because a new one couldn't be generated

export type FactResult =
  | { ok: true; fact: Fact; source: FactSource }
  | { ok: false; error: "no_movie" | "generation_failed" | "busy" };

// Everything the fact logic needs from the outside world. Production uses
// Prisma + OpenAI (see ./index.ts), tests pass in-memory fakes.
export interface FactStore {
  getFavoriteMovie(userId: string): Promise<string | null>;
  findLatestFact(userId: string, movieTitle: string): Promise<Fact | null>;
  saveFact(fact: Omit<Fact, "id"> & { userId: string }): Promise<Fact>;
  acquireLock(userId: string, token: string, expiresAt: Date, now: Date): Promise<boolean>;
  isLocked(userId: string, now: Date): Promise<boolean>;
  releaseLock(userId: string, token: string): Promise<void>;
}

export type FactDeps = {
  store: FactStore;
  generateFact: (movieTitle: string) => Promise<string>;
  now?: () => Date;
  sleep?: (ms: number) => Promise<void>;
};

export function isFresh(fact: Fact, now: Date) {
  return now.getTime() - fact.createdAt.getTime() < CACHE_WINDOW_MS;
}

/**
 * Returns a fun fact for the user's current favorite movie.
 *
 * Only takes a userId: the movie is read from the user's own row and facts
 * are always looked up by (userId, movieTitle), so a request can never see
 * another user's facts.
 */
export async function getFactForUser(userId: string, deps: FactDeps): Promise<FactResult> {
  const { store, generateFact, now = () => new Date(), sleep = defaultSleep } = deps;

  const movieTitle = await store.getFavoriteMovie(userId);
  if (!movieTitle) return { ok: false, error: "no_movie" };

  const latest = await store.findLatestFact(userId, movieTitle);
  if (latest && isFresh(latest, now())) {
    return { ok: true, fact: latest, source: "cache" };
  }

  const token = randomUUID();
  const lockedAt = now();
  const gotLock = await store.acquireLock(
    userId,
    token,
    new Date(lockedAt.getTime() + LOCK_TTL_MS),
    lockedAt,
  );

  if (!gotLock) {
    return waitForOtherRequest(userId, movieTitle, latest, { store, now, sleep });
  }

  try {
    // Check again now that we hold the lock. A request that was generating
    // while we read `latest` may have saved a fresh fact and released the lock
    // right before we took it.
    const current = await store.findLatestFact(userId, movieTitle);
    if (current && isFresh(current, now())) {
      return { ok: true, fact: current, source: "cache" };
    }

    try {
      const content = await generateFact(movieTitle);
      const fact = await store.saveFact({ userId, movieTitle, content, createdAt: now() });
      return { ok: true, fact, source: "generated" };
    } catch (error) {
      console.error("[facts] generation failed:", errorMessage(error));
      const fallback = current ?? latest;
      return fallback
        ? { ok: true, fact: fallback, source: "fallback" }
        : { ok: false, error: "generation_failed" };
    }
  } finally {
    // If this fails the lock still expires on its own after LOCK_TTL_MS.
    await store
      .releaseLock(userId, token)
      .catch((error) => console.error("[facts] failed to release lock:", errorMessage(error)));
  }
}

// Another request (a second tab, a quick refresh) is already calling OpenAI
// for this user. Wait for its fact instead of making a second call.
async function waitForOtherRequest(
  userId: string,
  movieTitle: string,
  latest: Fact | null,
  { store, now, sleep }: { store: FactStore; now: () => Date; sleep: (ms: number) => Promise<void> },
): Promise<FactResult> {
  const deadline = now().getTime() + WAIT_FOR_OTHER_REQUEST_MS;
  let otherRequestFailed = false;

  while (now().getTime() < deadline) {
    await sleep(POLL_INTERVAL_MS);

    // Order matters: the lock holder saves its fact *before* releasing the
    // lock, so if we see the lock gone, the fact query below is guaranteed to
    // see that fact (if there is one).
    const stillLocked = await store.isLocked(userId, now());
    const fact = await store.findLatestFact(userId, movieTitle);
    if (fact && isFresh(fact, now())) {
      return { ok: true, fact, source: "cache" };
    }
    if (!stillLocked) {
      otherRequestFailed = true;
      break;
    }
  }

  if (latest) return { ok: true, fact: latest, source: "fallback" };
  return { ok: false, error: otherRequestFailed ? "generation_failed" : "busy" };
}

function defaultSleep(ms: number) {
  return new Promise<void>((resolve) => setTimeout(resolve, ms));
}

function errorMessage(error: unknown) {
  return error instanceof Error ? error.message : String(error);
}
